#!/usr/bin/env python3
"""Write tools/isa/rules.h (the C copy of features.RULES) or check it is current.

    python3 -m tools.isa.gen_rules [--check]

The validity predicates are hand-written in scan.c; tests/isa/test_scan.py
proves the C and Python classifiers agree.

SPDX-License-Identifier: BSD-2-Clause-Patent
"""
import sys
from pathlib import Path

from tools.isa import features

OUT = Path(__file__).with_name("rules.h")


def render():
    lines = ["/* Generated by tools/isa/gen_rules.py from tools/isa/features.py. Do not edit.",
             " * SPDX-License-Identifier: BSD-2-Clause-Patent */",
             "#ifndef ISA_RULES_H", "#define ISA_RULES_H", "",
             "struct isa_rule { const char *name; unsigned mask, value; const char *needs; int fge; };",
             f"#define ISA_NRULES {len(features.RULES)}",
             "static const struct isa_rule isa_rules[ISA_NRULES] = {"]
    for name, mask, value, needs, fge in features.RULES:
        lines.append(f'\t{{ "{name}", 0x{mask:08X}u, 0x{value:08X}u, "{needs}", {int(fge)} }},')
    lines.append("};")
    tops = set()
    for _name, mask, value, _n, _f in features.RULES:
        m, v = mask >> 24, value >> 24
        tops |= {b for b in range(256) if (b & m) == v}
    lines.append("/* 1 for every top byte that some rule can match: a cheap pre-filter. */")
    lines.append("static const unsigned char isa_top[256] = {")
    for row in range(0, 256, 16):
        lines.append("\t" + ", ".join("1" if b in tops else "0" for b in range(row, row + 16)) + ",")
    lines.append("};")
    for k, (name, *_rest) in enumerate(features.RULES):
        macro = "R_" + name.upper().replace("-", "_")
        lines.append(f"#define {macro} {k}")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("tools/isa/rules.h is stale: run python3 -m tools.isa.gen_rules")
        print("rules.h up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
