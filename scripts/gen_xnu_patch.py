#!/usr/bin/env python3
"""Generate the FGE patch for XNU from kernel/fge and kernel/xnu.

    scripts/gen_xnu_patch.py XNU_CHECKOUT [--check]

XNU_CHECKOUT is a git checkout of apple-oss-distributions/xnu at the revision
UniXNU's OS profile pins (xnu-12377.121.6, ac9718fb1af6...). The script works
in a throw-away clone, so the checkout is not modified. Without --check it
writes kernel/patches/xnu-12377/0001-fge-undefined-instruction-emulation.patch;
with --check it fails if that file differs from what it would write (CI).

SPDX-License-Identifier: BSD-2-Clause-Patent
"""
import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATCH = ROOT / "kernel/patches/xnu-12377/0001-fge-undefined-instruction-emulation.patch"
XNU_REVISION = "ac9718fb1af618d5ce8678d0dc6e8a58f252216f"

SLEH_INCLUDE_ANCHOR = "#include <pexpert/arm64/board_config.h>\n"
SLEH_HOOK_ANCHOR = ("#endif /* CONFIG_XNUPOST */\n"
                    "\t\thandle_uncategorized(&context->ss);\n")
SLEH_HOOK = ("#endif /* CONFIG_XNUPOST */\n"
             "\t\t/* ARMv8.3-8.5 instructions on ARMv8.2 cores (macOS-Pad-6 FGE). */\n"
             "\t\tif (fge_xnu_handle(context)) {\n"
             "\t\t\tbreak;\n"
             "\t\t}\n"
             "\t\thandle_uncategorized(&context->ss);\n")
FILES_ANCHOR = "osfmk/arm64/sleh.c\t\t\tstandard\n"
FILES_ADD = ("osfmk/arm64/fge.c\t\t\tstandard\n"
             "osfmk/arm64/fge_xnu.c\t\t\tstandard\n")


def replace_once(text, old, new, what):
    n = text.count(old)
    if n != 1:
        sys.exit(f"{what}: anchor found {n} times, expected 1 (XNU revision changed?)")
    return text.replace(old, new)


def git(*args, cwd):
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True,
                          text=True).stdout


def generate(xnu):
    head = git("rev-parse", "HEAD", cwd=xnu).strip()
    if head != XNU_REVISION:
        sys.exit(f"{xnu} is at {head}, expected {XNU_REVISION}")
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "xnu"
        subprocess.run(["git", "clone", "-q", "--shared", "--no-checkout", str(xnu), str(work)],
                       check=True)
        git("checkout", "-q", XNU_REVISION, "--", "osfmk/arm64/sleh.c",
            "osfmk/conf/files.arm64", cwd=work)
        git("reset", "-q", XNU_REVISION, cwd=work)

        sleh = work / "osfmk/arm64/sleh.c"
        text = sleh.read_text()
        text = replace_once(text, SLEH_INCLUDE_ANCHOR,
                            SLEH_INCLUDE_ANCHOR + "#include <arm64/fge_xnu.h>\n", "sleh include")
        text = replace_once(text, SLEH_HOOK_ANCHOR, SLEH_HOOK, "sleh hook")
        sleh.write_text(text)

        files = work / "osfmk/conf/files.arm64"
        files.write_text(replace_once(files.read_text(), FILES_ANCHOR,
                                      FILES_ANCHOR + FILES_ADD, "files.arm64"))

        for src, dst in (("kernel/fge/fge.c", "osfmk/arm64/fge.c"),
                         ("kernel/fge/fge.h", "osfmk/arm64/fge.h"),
                         ("kernel/xnu/fge_xnu.c", "osfmk/arm64/fge_xnu.c"),
                         ("kernel/xnu/fge_xnu.h", "osfmk/arm64/fge_xnu.h")):
            shutil.copyfile(ROOT / src, work / dst)
        git("add", "-N", "osfmk/arm64/fge.c", "osfmk/arm64/fge.h", "osfmk/arm64/fge_xnu.c",
            "osfmk/arm64/fge_xnu.h", cwd=work)
        diff = git("diff", "--no-color", "--no-ext-diff", "-U3", "--", "osfmk/arm64/sleh.c",
                   "osfmk/conf/files.arm64", "osfmk/arm64/fge.c", "osfmk/arm64/fge.h",
                   "osfmk/arm64/fge_xnu.c", "osfmk/arm64/fge_xnu.h", cwd=work)
    header = (
        "From: macOS-Pad-6 contributors\n"
        "Subject: [PATCH] arm64: emulate ARMv8.3-8.5 instructions on ARMv8.2 cores (FGE)\n"
        "\n"
        f"Applies to apple-oss-distributions/xnu {XNU_REVISION} (xnu-12377.121.6).\n"
        "Generated by scripts/gen_xnu_patch.py from kernel/fge and kernel/xnu; edit\n"
        "those, not this file. Boot argument fge=0 disables the hook.\n"
        "\n"
        "---\n")
    return header + diff


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("xnu", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    patch = generate(args.xnu.resolve())
    if args.check:
        if not PATCH.exists() or PATCH.read_text() != patch:
            sys.exit(f"{PATCH.relative_to(ROOT)} is stale: run scripts/gen_xnu_patch.py")
        print("patch up to date")
        return
    PATCH.parent.mkdir(parents=True, exist_ok=True)
    PATCH.write_text(patch)
    print(f"wrote {PATCH.relative_to(ROOT)} ({patch.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
