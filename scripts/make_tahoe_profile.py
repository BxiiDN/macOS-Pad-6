#!/usr/bin/env python3
"""Write profiles/macos-26.5/profile.toml from measured evidence, in UniXNU's OS profile format.

    scripts/make_tahoe_profile.py --unixnu UNIXNU --evidence docs/evidence/tahoe-26.5

Every value comes from a file, never typed in:
  - kernelcache-*.json   (tools.isa.tahoe_audit kernelcache): IPSW, build, identity,
                          kernelcache SHA-256, AMFI policy address, fileset entries
  - images-26.5.json     (tools.isa.ipsw images): OS/SystemOS/AppOS image SHA-256 and
                          volume UUIDs; when absent, [root] is left out and the profile
                          says so
  - UniXNU's macos-27.3-26C5035r profile: the structure, the XNU tags of xnu-12377, and
    the prelink roots (all 67 are present in the 26.5 kernelcache, which the evidence checks)
  - distribution-macOS tag macos-265: xnu ac9718fb1af6 = xnu-12377.121.6 (constant below)

SPDX-License-Identifier: BSD-2-Clause-Patent
"""
import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILE_DIR = ROOT / "profiles/macos-26.5/unixnu"
DARWIN26_ONLY = {"darwin26-syscalls.patch", "darwin26-kpi.patch", "darwin26-shared-region.patch",
                 "macos-darwin26-kpi.patch"}
XNU_26_5 = ("12377.121.6", "ac9718fb1af618d5ce8678d0dc6e8a58f252216f")   # distribution-macOS macos-265


def q(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(q(x) for x in v) + "]"
    return json.dumps(v)


def table(name, items, comments=()):
    lines = [f"[{name}]"] + [f"# {c}" for c in comments]
    lines += [f"{json.dumps(k)} = {q(v)}" for k, v in items.items()]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--unixnu", type=Path, required=True)
    ap.add_argument("--evidence", type=Path, required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    ref = tomllib.loads((args.unixnu / "profiles/os/macos-27.3-26C5035r/profile.toml").read_text())
    kc_files = sorted(args.evidence.glob("kernelcache-*.json"))
    if len(kc_files) != 1:
        sys.exit(f"expected one kernelcache-*.json in {args.evidence}, found {len(kc_files)}")
    kc = json.loads(kc_files[0].read_text())
    src, audit = kc["source"], kc["audit"]
    if kc.get("prelink_roots_27_3", {}).get("missing_in_this_kernelcache"):
        sys.exit("some 27.3 prelink roots are missing from the 26.5 kernelcache; review them first")
    images = None
    img_path = args.evidence / f"images-{src['version']}.json"
    if img_path.exists():
        images = json.loads(img_path.read_text())["images"]
    adt_root, adt_product = src["adt"]["/"], src["adt"]["product"]
    name = f"macos-{src['version']}-{src['build']}"

    parts = [f"# UniXNU OS profile {name}: macOS Tahoe {src['version']} ({src['build']}) for an ARMv8.2 board\n"
             "# (Xiaomi Pad 6, SM8250). Generated by scripts/make_tahoe_profile.py from\n"
             f"# {args.evidence.relative_to(ROOT) if args.evidence.is_absolute() else args.evidence}; do not edit by hand.\n"
             "# Differences from UniXNU's macos-27.3-26C5035r: the kernel source is the release's own (no Darwin 26\n"
             "# backports), the identity is Mac mini M1 (J274AP), the oldest CPU Tahoe supports, and the board\n"
             "# (devices/pipa) applies the ARMv8.2 layer in its device series (null PAC, FGE). See docs/tahoe-26-report.md.\n"
             "# SPDX-License-Identifier: BSD-2-Clause-Patent\n"]
    os_t = dict(ref["os"])
    os_t.update({"name": name, "darwin": "25.5.0", "xnu_version": XNU_26_5[0], "xnu_revision": XNU_26_5[1],
                 "ios_version": src["version"]})
    parts.append(table("os", os_t, [
        "xnu-12377.121.6 is the macOS 26.5 kernel source (apple-oss-distributions/distribution-macOS macos-265).",
        "XNU_TARGET_OS_OSX on the iOS-platform kernel, as UniXNU's macOS profile builds it."]))
    parts.append(table("ipsw", {
        "url": src["ipsw"], "product": adt_root["model"], "version": src["version"], "build": src["build"],
        "device_class": src["device_class"], "chip_id": int(src["ap_chip_id"], 16),
        "board_id": int(src["ap_board_id"], 16), "fetch": ref["ipsw"]["fetch"]}))
    parts.append(table("kernel", {}))
    pre = dict(ref["kernel"]["prelink"])
    pre.update({"kernelcache_sha256": src["kernelcache_sha256"], "early_security_init": kc["early_security_init"]})
    parts.append(table("kernel.prelink", pre, [
        f"{src['member']} of the IPSW, decompressed ({len(audit.get('fileset_entries', []))} fileset entries).",
        "The roots are the macOS 27.3 profile's; every one is present in this kernelcache (evidence).",
        "Before prelinking for SM8250, tools/isa/pacstrip rewrites the collection's PAC instructions."]))
    parts.append(table("adt", {}))
    parts.append(table("adt.root", {}))
    parts.append(table("adt.root.string", {
        "model": adt_root["model"], "target-type": adt_root["target-type"],
        "target-sub-type": adt_root["target-sub-type"], "compatible": adt_root["target-sub-type"],
        "manufacturer": adt_root["manufacturer"], "secure-root-prefix": adt_root["secure-root-prefix"]},
        [f"From {src['components']['DeviceTree']['member']} ({adt_root.get('device-tree-tag')})."]))
    parts.append(table("adt.chosen", {}))
    chosen_str = {k: v for k, v in ref["adt"]["chosen"]["string"].items() if k not in ("boot-uuid", "apfs-preboot-uuid")}
    if images:
        os_uuid = next(v["uuid"] for v in images["OS"]["volumes"] if v.get("uuid"))
        chosen_str.update({"boot-uuid": os_uuid, "apfs-preboot-uuid": os_uuid})
    parts.append(table("adt.chosen.string", chosen_str))
    chosen_u32 = dict(ref["adt"]["chosen"]["u32"])
    chosen_u32["board-id"] = int(src["ap_board_id"], 16)
    parts.append(table("adt.chosen.u32", chosen_u32))
    parts.append(table("adt.chosen.asmb.u64", ref["adt"]["chosen"]["asmb"]["u64"]))
    parts.append(table("adt.chosen.asmb.u32", ref["adt"]["chosen"]["asmb"]["u32"]))
    parts.append(table("adt.product", {}))
    prod_keys = ["product-name", "product-description", "fdr-product-type", "sub-product-type", "unique-model",
                 "partition-style", "compatible-device-fallback", "compatible-app-variant",
                 "app-macho-architecture", "artwork-device-idiom", "artwork-display-gamut",
                 "artwork-dynamic-displaymode", "framebuffer-identifier", "chrome-identifier",
                 "graphics-featureset-class", "graphics-featureset-fallbacks", "mobiledevice-min-ver"]
    parts.append(table("adt.product.string", {k: adt_product[k] for k in prod_keys if isinstance(adt_product.get(k), str)},
                       [f"The product identity of {adt_root['model']}, from Apple's {src['components']['DeviceTree']['member']}."]))
    parts.append(table("adt.product.u32", {k: adt_product[k] for k in ("udid-version", "artwork-scale-factor",
                                                                         "artwork-device-subtype", "allow-32bit-apps")
                                           if isinstance(adt_product.get(k), int)}))
    for entry in ref.get("source", []):
        # UniXNU's macOS profile already pins the macOS 26.5 releases of these projects
        # (each commit is the one distribution-macOS macos-265 names; docs/tahoe-26-report.md).
        parts.append("[[source]]\n" + "\n".join(f"{json.dumps(k)} = {q(v)}" for k, v in entry.items()) + "\n")
    parts.append(f"[userdata]\nwindows = {q([])}\n".replace("windows = []", "windows = [\n" + ",\n".join(
        "  { " + ", ".join(f"{k} = {q(v)}" for k, v in w.items()) + " }" for w in ref["userdata"]["windows"]) + ",\n]"))
    if images:
        def vol(comp):
            vols = [v for v in images[comp]["volumes"] if v.get("uuid")]
            return vols[0]["uuid"]
        parts.append(table("root", {
            "os_volume_uuid": vol("OS"), "os_image_sha256": images["OS"]["image_sha256"],
            "systemos_volume_uuid": vol("Cryptex1,SystemOS"), "systemos_image_sha256": images["Cryptex1,SystemOS"]["image_sha256"],
            "app_volume_uuid": vol("Cryptex1,AppOS"), "app_image_sha256": images["Cryptex1,AppOS"]["image_sha256"]},
            ["Measured from the IPSW's disk images (AEA-decrypted with Apple's published keys) by tools.isa.ipsw images."]))
        parts.append(table("payload", {}))
        parts.append(table("payload.adt", {"root_match_volume_uuid": vol("OS")}))
    else:
        parts.append("# [root] and [payload.adt] (volume UUIDs and image digests) are not measured yet:\n"
                     "# run the 'images' job of .github/workflows/tahoe-audit.yml.\n")
    text = "\n".join(parts)
    tomllib.loads(text)                                  # must parse

    # The OS series: UniXNU's macOS 27.3 series without the Darwin 26 additions, with
    # paths into that profile's own patch directory (nothing copied).
    series = ["# OS patch series of " + name + ": UniXNU's macos-27.3-26C5035r series without the",
              "# patches that add Darwin 26 (macOS 27) system calls and KPIs; xnu-12377.121.6 is 26.5's own kernel.",
              "# Generated by scripts/make_tahoe_profile.py."]
    ref_series = args.unixnu / "profiles/os/macos-27.3-26C5035r/patches/xnu/series"
    for line in ref_series.read_text().splitlines():
        entry = line.strip()
        if not entry or entry.startswith("#"):
            continue
        if Path(entry).name in DARWIN26_ONLY:
            continue
        if not entry.startswith("arch:"):
            entry = "../../../macos-27.3-26C5035r/patches/" + entry[len("../"):]
        series.append(entry)
    files = {f"{name}/profile.toml": text,
             f"{name}/patches/xnu/series": "\n".join(series) + "\n",
             f"{name}/configs/macos.config": (args.unixnu / "profiles/os/macos-27.3-26C5035r/configs/macos.config").read_text()}
    stale = []
    for rel, content in files.items():
        path = PROFILE_DIR / rel
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        sys.exit(f"stale: {stale}; run scripts/make_tahoe_profile.py")
    if args.check:
        print("profile up to date")


if __name__ == "__main__":
    main()
